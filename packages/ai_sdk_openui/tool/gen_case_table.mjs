// Usage: node tool/gen_case_table.mjs > lib/src/iui/functions/case_table.dart
// Writes JavaScript's full (root-locale) case mappings per code point, which
// Dart's toUpperCase/toLowerCase lack (ß is SS, ﬁ is FI, newer scripts), so
// @Upper, @Lower and @Capitalize match the reference. Rerun after a Node upgrade.
const upper = [];
const lower = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp);
  if (s.toUpperCase() !== s) upper.push([cp, s.toUpperCase()]);
  // Final sigma depends on context; the Dart side handles U+03A3 itself.
  if (s.toLowerCase() !== s) lower.push([cp, s.toLowerCase()]);
}
const lit = (s) =>
  "'" + [...s].map((ch) => `\\u{${ch.codePointAt(0).toString(16).toUpperCase()}}`).join("") + "'";
const map = (rows) => rows.map(([cp, s]) => `  0x${cp.toString(16).toUpperCase()}: ${lit(s)},`).join("\n");
process.stdout.write(`// Generated by tool/gen_case_table.mjs with Node ${process.version}; do not edit.

/// JavaScript's toUpperCase of each code point that changes.
const jsUpperMap = <int, String>{
${map(upper)}
};

/// JavaScript's toLowerCase of each code point that changes, before the
/// final-sigma rule.
const jsLowerMap = <int, String>{
${map(lower)}
};
`);
