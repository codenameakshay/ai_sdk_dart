// Writes the currency prefixes en-US Intl.NumberFormat puts before a number
// that differ from the default "<CODE><no-break space>", so @Format matches
// the reference's toLocaleString, and the ISO 4217 codes ICU supports, which
// Money accepts. Rerun after a Node/ICU upgrade.
const format = (code) =>
  new Intl.NumberFormat("en-US", { style: "currency", currency: code }).formatToParts(1);
const prefix = (code) => {
  const parts = format(code);
  return parts.slice(0, parts.findIndex((p) => p.type === "integer")).map((p) => p.value).join("");
};
const codes = [];
for (let a = 65; a <= 90; a++)
  for (let b = 65; b <= 90; b++)
    for (let c = 65; c <= 90; c++) codes.push(String.fromCharCode(a, b, c));
const dart = (s) =>
  "'" +
  [...s]
    .map((ch) => {
      const cp = ch.codePointAt(0);
      if (ch === "$") return "\\$";
      if (ch === "'" || ch === "\\") return "\\" + ch;
      return cp >= 0x20 && cp < 0x7f ? ch : `\\u{${cp.toString(16).toUpperCase()}}`;
    })
    .join("") +
  "'";
const lines = codes
  .map((code) => [code, prefix(code)])
  .filter(([code, p]) => p !== `${code} `)
  .map(([code, p]) => `  '${code}': ${dart(p)},`);
process.stdout.write(`// Generated by tool/gen_currency_prefixes.mjs with Node ${process.version}; do not edit.

/// en-US currency prefixes other than the code and a no-break space.
const currencyPrefixes = <String, String>{
${lines.join("\n")}
};

/// The ISO 4217 codes ICU supports (\`Intl.supportedValuesOf("currency")\`).
const isoCurrencyCodes = <String>{
${Intl.supportedValuesOf("currency").map((code) => `  '${code}',`).join("\n")}
};
`);
