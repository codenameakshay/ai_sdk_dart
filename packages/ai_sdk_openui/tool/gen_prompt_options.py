"""Writes lib/src/iui/prompt_options.dart from the reference's prompt options.

Usage: python3 -I tool/gen_prompt_options.py <prompt_options.json> <out.dart>
The JSON comes from tool/extract_fixtures.mjs.
"""
import json, sys

src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src))

def lit(s):
    s = s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n')
    return "'" + s + "'"

po, dash = d['promptOptions'], d['dashboardPromptOptions']
rules = po['additionalRules']
assert dash['additionalRules'][:len(rules)] == rules
extra = dash['additionalRules'][len(rules):]
assert po['bindings'] is True and set(po) == {'bindings', 'additionalRules', 'examples'}
assert set(dash) == {'bindings', 'additionalRules', 'examples', 'tools', 'toolExamples'}
assert dash['examples'] == po['examples']

lines = [
    '// Generated by tool/gen_prompt_options.py from the reference prompt-options.ts. Do not edit.',
    '',
    "const List<String> chatRules = [",
    *[f'  {lit(r)},' for r in rules],
    '];',
    '',
    "const List<String> dashboardRules = [",
    *[f'  {lit(r)},' for r in extra],
    '];',
    '',
    "const List<String> chatExamples = [",
    *[f'  {lit(e)},' for e in po['examples']],
    '];',
    '',
    "const List<String> dashboardExamples = [",
    *[f'  {lit(e)},' for e in dash['toolExamples']],
    '];',
    '',
]
open(out, 'w').write('\n'.join(lines))
