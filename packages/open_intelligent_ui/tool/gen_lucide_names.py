"""Writes lib/src/components/lucide_names.dart: lucide icon name -> codepoint.

Usage:
  python3 -I tool/gen_lucide_names.py <lucide_icons_flutter>/assets/codepoints.json \
      <lucide-react@0.562.0>/dist/esm/dynamicIconImports.js lib/src/components/lucide_names.dart

The name set is lucide-react's (the reference's `iconNames`, aliases included);
each name resolves to its canonical icon's codepoint in assets/fonts/lucide.ttf,
which is that package's font.
"""
import json, re, sys

font_src, react_src, out = sys.argv[1:4]
font = json.load(open(font_src))
table = re.findall(r'"([a-z0-9-]+)": \(\) => import\(\'\./icons/([a-z0-9-]+)\.js\'\)', open(react_src).read())
assert len(table) > 1500, len(table)
names, missing = {}, []
for name, canonical in table:
    cp = font.get(canonical, font.get(name))
    if cp is None:
        missing.append(name)
    else:
        names[name] = cp
lines = ['// Generated by tool/gen_lucide_names.py from lucide-react 0.562.0 names', '// and the vendored lucide font. Do not edit.', '',
         'const Map<String, int> lucideCodepoints = {']
lines += [f"  '{n}': 0x{c:x}," for n, c in sorted(names.items())]
lines += ['};', '']
open(out, 'w').write('\n'.join(lines))
print(len(names), 'names,', len(missing), 'not in the font:', ' '.join(missing))
