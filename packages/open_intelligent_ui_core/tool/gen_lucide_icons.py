"""Writes lib/src/components/lucide_icons.dart: every lucide-react icon as SVG path data.

Usage:
  python3 -I tool/gen_lucide_icons.py <lucide-react@0.562.0 package dir> lib/src/components/lucide_icons.dart

<package dir> is the unpacked npm tarball's `package` folder. The name set is
lucide-react's `iconNames` (dynamicIconImports.js, aliases included); each icon's
elements (icons/<name>.js, `__iconNode`) become one path on lucide's 24 by 24 grid.
"""
import json, os, re, sys

pkg, out = sys.argv[1:3]
esm = os.path.join(pkg, 'dist', 'esm')
version = json.load(open(os.path.join(pkg, 'package.json')))['version']
assert version == '0.562.0', version
table = re.findall(r'"([a-z0-9-]+)": \(\) => import\(\'\./icons/([a-z0-9-]+)\.js\'\)',
                   open(os.path.join(esm, 'dynamicIconImports.js')).read())
assert len(table) > 1500, len(table)

ALLOWED = {
    'path': {'d'}, 'circle': {'cx', 'cy', 'r'}, 'ellipse': {'cx', 'cy', 'rx', 'ry'},
    'line': {'x1', 'y1', 'x2', 'y2'}, 'polyline': {'points'}, 'polygon': {'points'},
    'rect': {'x', 'y', 'width', 'height', 'rx', 'ry'},
}

def num(v):
    s = ('%.4f' % v).rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s

def points(text):
    v = [float(p) for p in re.split(r'[\s,]+', text.strip())]
    assert len(v) % 2 == 0, text
    return ['%s %s' % (num(v[i]), num(v[i + 1])) for i in range(0, len(v), 2)]

def to_path(tag, a):
    f = lambda k, d=0.0: float(a.get(k, d))
    if tag == 'path':
        return a['d']
    if tag in ('circle', 'ellipse'):
        rx = f('r') if tag == 'circle' else f('rx')
        ry = f('r') if tag == 'circle' else f('ry')
        cx, cy = f('cx'), f('cy')
        arc = 'a%s %s 0 1 0 ' % (num(rx), num(ry))
        return 'M%s %s%s%s 0%s%s 0Z' % (num(cx - rx), num(cy), arc, num(2 * rx), arc, num(-2 * rx))
    if tag == 'line':
        return 'M%s %sL%s %s' % (num(f('x1')), num(f('y1')), num(f('x2')), num(f('y2')))
    if tag in ('polyline', 'polygon'):
        p = points(a['points'])
        return 'M' + 'L'.join(p) + ('Z' if tag == 'polygon' else '')
    if tag == 'rect':
        x, y, w, h = f('x'), f('y'), f('width'), f('height')
        rx = f('rx', a.get('ry', 0)); ry = f('ry', a.get('rx', 0))
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx <= 0 or ry <= 0:
            return 'M%s %sh%sv%sh%sZ' % (num(x), num(y), num(w), num(h), num(-w))
        arc = lambda dx, dy: 'a%s %s 0 0 1 %s %s' % (num(rx), num(ry), num(dx), num(dy))
        return ('M%s %sh%s' % (num(x + rx), num(y), num(w - 2 * rx)) + arc(rx, ry) + 'v' + num(h - 2 * ry)
                + arc(-rx, ry) + 'h' + num(-(w - 2 * rx)) + arc(-rx, -ry) + 'v' + num(-(h - 2 * ry)) + arc(rx, -ry) + 'Z')
    raise SystemExit('unknown element ' + tag)

icons = {}
for canonical in sorted({c for _, c in table}):
    src = open(os.path.join(esm, 'icons', canonical + '.js')).read()
    m = re.search(r'const __iconNode = (\[.*?\]);\n', src, re.S)
    assert m, canonical
    nodes = json.loads(re.sub(r'(\b[A-Za-z]\w*): ', r'"\1": ', m.group(1)))
    stroke, fill = [], []
    for tag, attrs in nodes:
        attrs = dict(attrs)
        attrs.pop('key', None)
        filled = attrs.pop('fill', None)
        assert filled in (None, 'currentColor'), (canonical, filled)
        extra = set(attrs) - ALLOWED.get(tag, set())
        assert not extra, (canonical, tag, extra)
        d = to_path(tag, attrs)
        assert not set(d) & set("'$\\|"), (canonical, d)
        stroke.append(d)
        if filled:
            fill.append(d)
    icons[canonical] = ('|'.join(stroke), '|'.join(fill) or None)

dart = lambda s: "'" + s + "'"
notice = open(os.path.join(pkg, 'LICENSE')).read().strip().splitlines()
lines = ['// Generated by tool/gen_lucide_icons.py from lucide-react %s. Do not edit.' % version, '//',
         '// The icon outlines below are Lucide\'s, under this licence:', '//']
lines += [('// ' + l).rstrip() for l in notice]
lines += ['',
         '/// Lucide icons on a 24 by 24 grid as SVG path data, one element per',
         '/// `|`-separated part: the stroked elements, then those also filled (or null).',
         'const Map<String, (String, String?)> lucideIcons = {']
lines += ["  '%s': (%s, %s)," % (n, dart(s), dart(f) if f else 'null') for n, (s, f) in icons.items()]
lines += ['};', '', '/// lucide-react names that are aliases of an icon in [lucideIcons].',
          'const Map<String, String> lucideAliases = {']
lines += ["  '%s': '%s'," % (n, c) for n, c in sorted(table) if n != c]
lines += ['};', '']
open(out, 'w').write('\n'.join(lines))
print(len(icons), 'icons,', sum(1 for n, c in table if n != c), 'aliases,', os.path.getsize(out), 'bytes')
